export const STATE_ORDER = GAME_STATES.map((s) => s.slug);

/** Regular states only (excludes the final Incredible India tour). */
export const REGION_STATES = GAME_STATES.filter((s) => s.slug !== "india");

export function getGameState(slug: string): GameStateLevel | undefined {
  return GAME_STATES.find((s) => s.slug === slug);
}

export function getNextState(slug: string): GameStateLevel | undefined {
  const idx = STATE_ORDER.indexOf(slug);
  if (idx < 0 || idx >= STATE_ORDER.length - 1) return undefined;
  return GAME_STATES[idx + 1];
}

export function isIndiaFinale(slug: string): boolean {
  return slug === "india";
}
